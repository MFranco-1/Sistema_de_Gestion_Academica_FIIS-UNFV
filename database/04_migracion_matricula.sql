UPDATE periodo_academico
SET anio = CAST(SUBSTRING(cod_periodo FROM 1 FOR 4) AS INTEGER),
    tipo_periodo = CASE
        WHEN cod_periodo LIKE '%-I' THEN 'I'
        WHEN cod_periodo LIKE '%-II' THEN 'II'
        ELSE 'VERANO'
    END
WHERE anio IS NULL OR tipo_periodo IS NULL;

